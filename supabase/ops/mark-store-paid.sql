-- ============================================================================
-- تفعيل الدفع يدوياً لمحل معيّن — نسخة/لصق في SQL Editor عند استلام الدفع
-- ============================================================================
-- هذا ليس ملف migration (لا تشغّله مرة واحدة نهائياً) — بل قالب تُعيد استعماله
-- في كل مرة يدفع فيها صاحب محل. عدّل السطر الذي فيه WHERE ليطابق محله، ثم شغّل.
--
-- ملاحظة: SQL Editor في لوحة Supabase يعمل بصلاحيات كاملة (يتجاوز RLS)،
-- لذا هذا الاستعلام يعمل حتى لو كانت سياسات stores تسمح فقط لصاحب المحل
-- بتعديل صفّه عبر التطبيق نفسه.
--
-- المنطق: نمدّد الاشتراك شهراً واحداً بدءاً من "الأبعد" بين اليوم و paid_until
-- الحالي (إن كان لا يزال سارياً) — حتى لا تضيع أيام دفعها العميل مسبقاً لو جدّد
-- قبل الموعد.
-- ============================================================================

update public.stores
set paid_until = greatest(coalesce(paid_until, now()), now()) + interval '1 month'
where name = 'اسم المحل هنا'; -- 👈 عدّل هذا ليطابق اسم المحل بالضبط (أو استعمل owner_id/id إن كان أدق)

