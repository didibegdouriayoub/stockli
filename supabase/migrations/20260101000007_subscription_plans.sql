-- ============================================================================
-- نُضيف عمود plan فقط ليعرف المشرف أي خطة يشترك فيها كل محل حالياً (لعرضها في
-- لوحة المشرف بجانب تاريخ الانتهاء الدقيق). القيمة null تعني "لا خطة بعد"
-- (لا يزال في التجربة المجانية ولم يدفع أبداً).
-- ============================================================================

alter table public.stores
  add column if not exists plan text
  check (plan is null or plan in ('monthly', 'six_months', 'yearly'));
